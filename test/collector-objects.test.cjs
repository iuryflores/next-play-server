// Banco descartável exclusivo; o S3 é simulado para testar falhas e privacidade sem arquivos reais.
process.env.NODE_ENV = 'test';
process.env.EMAIL_VERIFICATION_REQUIRED = 'false';
process.env.CLIENT_ORIGIN = 'http://localhost:5174';
process.env.SWAGGER_ENABLED = 'true';
const { randomUUID } = require('node:crypto');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { ServiceUnavailableException } = require('@nestjs/common');
const database = 'nextplay_objects_test_' + randomUUID().replaceAll('-', '');
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/' + database;
const { createApp } = require('../dist/bootstrap');
const { getConnectionToken, getModelToken } = require('@nestjs/mongoose');
const { CollectorPhotoStorage } = require('../dist/collector/collector-photo-storage');

test('objetos manuais têm categorias, fotos privadas e ciclo de vida independente do acompanhamento', async t => {
  const app = await createApp(), db = app.get(getConnectionToken());
  t.after(async () => { try { assert.match(database,/^nextplay_objects_test_[a-f0-9]{32}$/); assert.equal(db.name,database); await db.dropDatabase(); } finally { await app.close(); } });
  await app.listen(0,'127.0.0.1');
  const base=await app.getUrl();
  const request=(path,method='GET',body,cookie,origin=process.env.CLIENT_ORIGIN)=>fetch(base+'/api'+path,{method,redirect:'manual',headers:{Origin:origin,...(body?{'Content-Type':'application/json'}:{}),...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
  async function account(email) { const r=await request('/auth/register','POST',{email,password:'Objects-test-password-123!'});assert.equal(r.status,201);return r.headers.get('set-cookie').split(';')[0]; }
  const a=await account('objects-a@example.test'), b=await account('objects-b@example.test');
  const storage=app.get(CollectorPhotoStorage), removed=[];let uploads=0;
  storage.upload=async(owner,buffer)=>{assert.equal(buffer.length,12000);return `uploads/collector/${owner}/photo-${++uploads}.jpg`;};
  storage.remove=async key=>removed.push(key);
  storage.signedUrl=async key=>'https://example.test/private-photo?key='+encodeURIComponent(key);
  const bytes=Buffer.alloc(12000);bytes[0]=255;bytes[1]=216;bytes[bytes.length-2]=255;bytes[bytes.length-1]=217;
  const photo='data:image/jpeg;base64,'+bytes.toString('base64');
  const input={kind:'other',title:' Ferrari F40 ',category:' Carrinhos ',format:'physical',notes:'Exemplar privado',photo};
  const path='/collector/copies';
  assert.equal((await request(path,'POST',input)).status,401);
  assert.equal((await request(path,'POST',input,a,'https://evil.test')).status,403);
  for(const body of [{...input,category:undefined},{...input,category:'  '},{...input,category:'x'.repeat(61)},{...input,format:'digital'},{...input,catalogId:'tmdb:movie:1'},{...input,photo:'https://evil.test/image.jpg'},{...input,photo:'data:image/jpeg;base64,YWJjZA=='},{...input,photo:'x'.repeat(600001)},{...input,photoKey:'uploads/collector/another/photo.jpg'},{...input,kind:'book'}]) assert.equal((await request(path,'POST',body,a)).status,400);
  assert.equal(uploads,0);
  const created=await request(path,'POST',input,a);assert.equal(created.status,201);
  const copy=(await created.json()).copy;
  assert.equal(copy.kind,'other');assert.equal(copy.title,'Ferrari F40');assert.equal(copy.category,'Carrinhos');
  assert.equal(copy.photo,undefined);assert.equal(copy.photoKey,undefined);assert.match(copy.coverUrl,new RegExp('^/api/collector/copies/'+copy.id+'/photo\\?v='));
  assert.equal((await request(path+'/'+copy.id+'/photo')).status,401);
  assert.equal((await request(path+'/'+copy.id+'/photo','GET',undefined,b)).status,404);
  const image=await request(path+'/'+copy.id+'/photo','GET',undefined,a);assert.equal(image.status,302);assert.match(image.headers.get('location'),/^https:\/\/example.test\/private-photo/);assert.equal(image.headers.get('cache-control'),'no-store');
  assert.deepEqual((await (await request(path,'GET',undefined,b)).json()).copies,[]);
  assert.equal((await request(path+'/'+copy.id,'PATCH',input,b)).status,404);
  assert.equal((await request(path+'/'+copy.id,'DELETE',undefined,b)).status,404);
  const {photo: _photo,...withoutPhoto}=input;
  const update=await request(path+'/'+copy.id,'PATCH',{...withoutPhoto,title:'Ferrari F40 atualizada'},a);assert.equal(update.status,200);assert.equal(uploads,1);assert.equal(removed.length,0);
  assert.equal((await request(path+'/'+copy.id,'PATCH',input,a)).status,200);assert.equal(uploads,2);assert.match(removed[0],/photo-1.jpg$/);
  const replaced=(await db.collection('collector_copies').findOne({title:'Ferrari F40'})).photoKey;
  const normalUpload=storage.upload;
  storage.upload=async()=>{throw new ServiceUnavailableException('Falha simulada');};
  assert.equal((await request(path+'/'+copy.id,'PATCH',input,a)).status,503);
  assert.equal((await db.collection('collector_copies').findOne({title:'Ferrari F40'})).photoKey,replaced);
  storage.upload=async(owner,buffer)=>{const key=await normalUpload(owner,buffer);await db.collection('collector_copies').updateOne({photoKey:replaced},{$inc:{__v:1}});return key;};
  assert.equal((await request(path+'/'+copy.id,'PATCH',input,a)).status,409);assert.match(removed.at(-1),/photo-3.jpg$/);
  assert.equal((await db.collection('collector_copies').findOne({title:'Ferrari F40'})).photoKey,replaced);
  storage.upload=normalUpload;
  assert.equal((await request(path+'/'+copy.id,'PATCH',{...withoutPhoto,photo:''},a)).status,200);assert.ok(removed.includes(replaced));
  assert.equal((await request(path+'/'+copy.id+'/photo','GET',undefined,a)).status,404);
  assert.equal((await request(path+'/'+copy.id,'PATCH',input,a)).status,200);
  assert.equal((await request(path+'/'+copy.id,'DELETE',undefined,a)).status,204);assert.match(removed.at(-1),/photo-4.jpg$/);
  const model=app.get(getModelToken('CollectorCopy')), create=model.create;
  model.create=async()=>{throw new ServiceUnavailableException('Falha ao persistir');};
  try { assert.equal((await request(path,'POST',input,a)).status,503);assert.match(removed.at(-1),/photo-5.jpg$/); } finally { model.create=create; }
  for(const category of ['Carrinhos','Action figures']) assert.equal((await request(path,'POST',{...withoutPhoto,category},a)).status,201);
  assert.equal(await db.collection('library_items').countDocuments(),0);assert.equal(await db.collection('episode_progress').countDocuments(),0);
  const spec=await (await request('/docs-json')).json();
  assert.ok(spec.components.schemas.CollectorCopyDto.properties.kind.enum.includes('other'));
  assert.equal(spec.components.schemas.CollectorCopyDto.properties.category.maxLength,60);
  assert.equal(spec.components.schemas.CollectorCopyDto.properties.photo.maxLength,600000);
  assert.ok(spec.paths['/api/collector/copies/{id}/photo'].get.responses['302']);
  assert.ok(spec.paths['/api/collector/copies'].post.responses['503']);
});
