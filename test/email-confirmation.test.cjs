const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const database = 'nextplay_confirmation_test_' + randomUUID().replaceAll('-', '');
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/' + database;
process.env.CLIENT_ORIGIN = 'http://localhost:5174'; process.env.NODE_ENV = 'test'; process.env.ALLOW_REGISTRATION = 'true';
process.env.EMAIL_VERIFICATION_REQUIRED = 'true';
const { createApp } = require('../dist/bootstrap');
const { RecoveryMailer } = require('../dist/auth/password-recovery');
const { EmailConfirmation } = require('../dist/auth/email-confirmation');
const { hashToken } = require('../dist/auth/password');
const { recoveryEmail } = require('../dist/auth/recovery-email');
const { getConnectionToken } = require('@nestjs/mongoose');

test('new accounts confirm email before login, with expiry, resend and atomic single use; legacy accounts retain access', async t => {
  const app = await createApp(); await app.listen(0, '127.0.0.1');
  const db = app.get(getConnectionToken()), base = await app.getUrl();
  t.after(async () => { try { assert.equal(db.name, database); assert.match(database, /^nextplay_confirmation_test_[a-f0-9]{32}$/); await db.dropDatabase(); } finally { await app.close(); } });
  const mails = [], mailer = app.get(RecoveryMailer);
  mailer.send = async (to, link, purpose) => mails.push({ to, link, purpose });
  const call = (route, body, origin = process.env.CLIENT_ORIGIN) => fetch(base + '/api/auth/' + route, { method: 'POST', headers: { origin, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  let email = 'new@example.test'; const password = 'Original-password-123!';
  let r = await call('register', { email, password }); assert.equal(r.status, 201);
  assert.equal((await r.json()).requiresVerification, true); assert.equal(r.headers.get('set-cookie'), null);
  assert.equal((await call('login', { email, password })).status, 403);
  assert.equal(mails.length, 1); assert.equal(mails[0].purpose, 'verification');
  const tokenFor = mail => new URLSearchParams(new URL(mail.link).hash.slice(1)).get('verify-email');
  const token = tokenFor(mails[0]);
  let user = await db.collection('users').findOne({ email });
  assert.equal(user.verificationTokenHash, hashToken(token));
  assert.ok(user.verificationExpiresAt > new Date(Date.now() + 23 * 3600000));
  assert.match(recoveryEmail(mails[0].link, 'verification').html, /Confirmar meu e-mail/);
  assert.match(recoveryEmail(mails[0].link, 'verification').text, /24 horas/);
  assert.equal((await call('confirm-email', { token }, 'https://evil.test')).status, 403);
  const generic = await (await call('resend-confirmation', { email: 'absent@example.test' })).json();
  assert.deepEqual(await (await call('resend-confirmation', { email })).json(), generic); assert.equal(mails.length, 1);
  await db.collection('users').updateOne({ email }, { $set: { verificationExpiresAt: new Date(0) } });
  assert.equal((await call('confirm-email', { token })).status, 400);
  await db.collection('users').updateOne({ email }, { $unset: { verificationRequestedAt: 1 } });
  await call('resend-confirmation', { email }); assert.equal(mails.length, 2);
  assert.equal((await call('confirm-email', { token })).status, 400);
  const fresh = tokenFor(mails[1]);
  const attempts = await Promise.all([call('confirm-email', { token: fresh }), call('confirm-email', { token: fresh })]);
  assert.deepEqual(attempts.map(r => r.status).sort(), [200, 400]);
  r = await call('login', { email, password }); assert.equal(r.status, 200); assert.ok(r.headers.get('set-cookie'));
  user = await db.collection('users').findOne({ email }); assert.ok(user.emailVerifiedAt); assert.equal(user.verificationTokenHash, undefined);
  const cookie = r.headers.get('set-cookie').split(';')[0];
  const changedEmail = 'changed@example.test';
  const profile = await fetch(base + '/api/auth/profile', { method: 'POST', headers: { origin: process.env.CLIENT_ORIGIN, 'Content-Type': 'application/json', cookie }, body: JSON.stringify({ displayName: 'Player', email: changedEmail, currentPassword: password }) });
  assert.equal(profile.status, 200); assert.equal((await profile.json()).user.requiresVerification, true);
  email = changedEmail;
  assert.equal((await call('login', { email, password })).status, 403);
  assert.equal(mails.length, 3);
  assert.equal((await db.collection('users').findOne({ email })).emailVerifiedAt, undefined);
  // Contas migradas sem o marcador de obrigatoriedade continuam funcionando.
  await db.collection('users').updateOne({ email }, { $unset: { verificationRequired: 1, emailVerifiedAt: 1 } });
  assert.equal((await call('login', { email, password })).status, 200);
  // Falha de envio não gera sessão nem deixa token não entregue válido.
  mailer.send = async () => { throw new Error('SMTP offline'); };
  const failedEmail = 'failed@example.test';
  r = await call('register', { email: failedEmail, password }); assert.equal(r.status, 201); assert.equal(r.headers.get('set-cookie'), null);
  assert.equal((await db.collection('users').findOne({ email: failedEmail })).verificationTokenHash, undefined);
  await db.collection('users').updateOne({ email: failedEmail }, { $unset: { verificationRequestedAt: 1 } });
  mailer.send = async (to, link, purpose) => mails.push({ to, link, purpose });
  await app.get(EmailConfirmation).request(failedEmail); assert.equal(mails.length, 4);
});
