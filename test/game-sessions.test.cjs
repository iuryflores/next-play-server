const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
// Testes restritos ao banco local descartável; não utiliza o histórico real de jogos.
const database = 'nextplay_game_sessions_test_' + randomUUID().replaceAll('-', '');
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/' + database;
process.env.NODE_ENV = 'test'; process.env.CLIENT_ORIGIN = 'http://localhost:5174';
process.env.ALLOW_REGISTRATION = 'true'; process.env.EMAIL_VERIFICATION_REQUIRED = 'false'; process.env.SWAGGER_ENABLED = 'true';
const { createApp } = require('../dist/bootstrap');
const { getConnectionToken } = require('@nestjs/mongoose');
test('sessões preservam saldo anterior, datas e total sob repetição, edição e concorrência', async t => {
  const app = await createApp(); await app.listen(0, '127.0.0.1');
  const base = await app.getUrl(), db = app.get(getConnectionToken());
  t.after(async () => { try {
    assert.match(database, /^nextplay_game_sessions_test_[a-f0-9]{32}$/); assert.equal(db.name, database); await db.dropDatabase();
  } finally { await app.close(); } });
  const call = (path, method = 'GET', cookie, body, origin = process.env.CLIENT_ORIGIN) => fetch(base + '/api' + path, { method, headers: { origin, ...(cookie ? { cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const register = async name => { const response = await call('/auth/register', 'POST', undefined, { email: name + '@example.test', password: 'Long-test-password-123!' }); assert.equal(response.status, 201); return response.headers.get('set-cookie').split(';')[0]; };
  const a = await register('sessions-a'), b = await register('sessions-b');
  const response = await call('/library', 'POST', a, { title: 'Jogo', kind: 'game', status: 'planned', playtimeMinutes: 90, notes: 'Notas privadas', platform: 'PC' });
  const game = (await response.json()).item, path = `/library/${game.id}/game-sessions`;
  const list = async () => { const r = await call(path, 'GET', a); assert.equal(r.status, 200); return r.json(); };
  let history = await list();
  assert.equal(history.baselineMinutes, 90); assert.equal(history.sessionCount, 0); assert.equal(history.lastPlayedOn, null);
  assert.equal((await call(path)).status, 401); assert.equal((await call(path, 'GET', b)).status, 404);
  const first = { id: randomUUID(), mode: 'add', minutes: 50, playedOn: '2026-10-01', timeZone: 'America/Sao_Paulo' };
  assert.equal((await call(path, 'POST', a, first, 'https://evil.example')).status, 403);
  assert.equal((await call(path, 'POST', b, first)).status, 404);
  const add = async payload => { const r = await call(path, 'POST', a, payload); assert.equal(r.status, 201, await r.clone().text()); return r.json(); };
  history = await add(first);
  assert.equal(history.playtimeMinutes, 140); assert.equal(history.baselineMinutes, 90); assert.equal(history.status, 'active');
  assert.equal(history.lastPlayedOn, '2026-10-01');
  assert.equal((await add(first)).playtimeMinutes, 140, 'reenviar não duplica sessão');
  const second = { id: randomUUID(), mode: 'total', minutes: 200, expectedTotal: 140, playedOn: '2026-10-02' };
  history = await add(second);
  assert.equal(history.sessions.find(row => row.id === second.id).minutes, 60);
  assert.equal((await add(second)).playtimeMinutes, 200);
  assert.equal((await call(path, 'POST', a, { ...second, minutes: 300 })).status, 409, 'chave repetida não aceita outros valores');
  for (const patch of [{ playedOn: '2099-01-01' }, { playedOn: '2026-02-30' }, { minutes: 0 }, { minutes: 1441 }, { minutes: 1.5 }, { timeZone: 'Bad/Zone' }, { ownerId: 'forged' }]) {
    assert.equal((await call(path, 'POST', a, { ...first, id: randomUUID(), ...patch })).status, 400);
  }
  assert.equal((await call(path, 'POST', a, { ...second, id: randomUUID(), expectedTotal: 90 })).status, 409);
  assert.equal((await call(path, 'POST', a, { ...second, id: randomUUID(), expectedTotal: 200, minutes: 190 })).status, 400);
  let r = await call(path + '/' + first.id, 'PATCH', a, { playedOn: '2026-10-03', minutes: 80 });
  assert.equal(r.status, 200); history = await r.json();
  assert.equal(history.playtimeMinutes, 230); assert.equal(history.baselineMinutes, 90); assert.equal(history.lastPlayedOn, '2026-10-03');
  assert.equal((await call(path + '/' + first.id, 'PATCH', b, { playedOn: '2026-10-03', minutes: 90 })).status, 404);
  assert.equal((await call(path + '/' + first.id, 'DELETE', b)).status, 404);
  history = await (await call(path + '/' + first.id, 'DELETE', a)).json();
  assert.equal(history.playtimeMinutes, 150); assert.equal(history.lastPlayedOn, '2026-10-02');
  history = await (await call(path + '/' + second.id, 'DELETE', a)).json();
  assert.equal(history.playtimeMinutes, 90); assert.equal(history.lastPlayedOn, null);
  await add({ ...first, id: randomUUID(), minutes: 290 });
  await Promise.all([30, 40].map(minutes => add({ ...first, id: randomUUID(), minutes })));
  history = await list();
  assert.equal(history.playtimeMinutes, 450); assert.equal(history.sessionCount, 3);
  r = await call(`/library/${game.id}/playtime`, 'PATCH', a, { mode: 'total', minutes: 500, expectedTotal: 450 });
  assert.equal(r.status, 200); history = await list();
  assert.equal(history.baselineMinutes, 140); assert.equal(history.sessionCount, 3);
  assert.equal((await call(`/library/${game.id}/playtime`, 'PATCH', a, { mode: 'total', minutes: 100, expectedTotal: 500 })).status, 400);
  assert.equal((await call(`/library/${game.id}/playtime`, 'PATCH', a, { mode: 'total', minutes: 550, expectedTotal: 450 })).status, 409);
  assert.equal((await call(`/library/${game.id}`, 'PATCH', a, { title: 'Jogo', kind: 'game', status: 'active', playtimeMinutes: 100 })).status, 400);
  r = await call(`/library/${game.id}`, 'PATCH', a, { title: 'Jogo', kind: 'game', status: 'completed', notes: 'Notas privadas', completedOn: '2026-10-20' });
  assert.equal(r.status, 200); assert.equal((await r.json()).item.playtimeMinutes, 500);
  history = await add({ ...first, id: randomUUID(), minutes: 10, playedOn: '2026-10-04' });
  assert.equal(history.status, 'completed', 'jogar novamente não desfaz conclusão');
  const cards = await (await call('/library', 'GET', a)).json();
  const card = cards.items.find(row => row.id === game.id);
  assert.equal(card.lastPlayedOn, '2026-10-04'); assert.equal(card.platform, 'PC'); assert.equal(card.notes, 'Notas privadas');
  assert.equal(card.gameSessions, undefined, 'lista geral não expõe histórico completo');
  for (let i = 0; i < 28; i++) await add({ ...first, id: randomUUID(), minutes: 1 });
  history = await list(); assert.equal(history.sessions.length, 30); assert.equal(history.nextOffset, 30);
  const next = await (await call(path + '?offset=30', 'GET', a)).json();
  assert.equal(next.sessions.length, 2); assert.equal(next.nextOffset, null);
  assert.equal(new Set([...history.sessions, ...next.sessions].map(row => row.id)).size, 32);
  assert.equal((await call(path + '?offset=-1', 'GET', a)).status, 400);
  const spec = await (await call('/docs-json')).json();
  assert.ok(spec.paths['/api/library/{id}/game-sessions']); assert.ok(spec.components.schemas.SessionsViewDto);
  const shared = { ...first, id: randomUUID(), minutes: 1 };
  await Promise.all([add(shared), add(shared)]);
  assert.equal((await list()).sessionCount, 33, 'reenviar simultaneamente a mesma sessão também é idempotente');
});
