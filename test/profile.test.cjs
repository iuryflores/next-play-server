// Este cenário testa o fluxo legado; confirmação obrigatória tem suíte própria.
process.env.EMAIL_VERIFICATION_REQUIRED = 'false';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const database = 'nextplay_profile_test_' + randomUUID().replaceAll('-', '');
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/' + database;
process.env.CLIENT_ORIGIN = 'http://localhost:5174'; process.env.NODE_ENV = 'test'; process.env.ALLOW_REGISTRATION = 'true';
const { createApp } = require('../dist/bootstrap');
const { getConnectionToken } = require('@nestjs/mongoose');
const { AvatarStorage } = require('../dist/auth/avatar-storage');
test('profile updates are private, persisted, validated and email changes require the current password', async t => {
  const app = await createApp(); await app.listen(0, '127.0.0.1'); const base = await app.getUrl(); const db = app.get(getConnectionToken());
  const storage = app.get(AvatarStorage), uploaded = [], removed = [];
  storage.upload = async (owner, image) => { const key = `uploads/avatars/${owner}/${uploaded.length}.jpg`; uploaded.push({ key, image }); return key; };
  storage.remove = async key => { removed.push(key); };
  storage.signedUrl = async key => `https://example.test/${key}?signed=1`;
  t.after(async () => { try { assert.match(database, /^nextplay_profile_test_[a-f0-9]{32}$/); assert.equal(db.name, database); await db.dropDatabase(); } finally { await app.close(); } });
  const call = (path, body, cookie, origin = process.env.CLIENT_ORIGIN) => fetch(base + '/api/' + path, { method: body ? 'POST' : 'GET', headers: { origin, ...(cookie ? { cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const password = 'Long-test-password-123!';
  const register = async email => { const r = await call('auth/register', { email, password }); assert.equal(r.status, 201); return r.headers.get('set-cookie').split(';')[0]; };
  const a = await register('a@example.test'), b = await register('b@example.test');
  const profile = { displayName: ' Alice ', email: 'a@example.test', avatar: '' };
  assert.equal((await call('auth/profile', profile)).status, 401);
  assert.equal((await call('auth/profile', profile, a, 'https://evil.example')).status, 403);
  assert.equal((await call('auth/profile', { ...profile, displayName: '   ' }, a)).status, 400);
  assert.equal((await call('auth/profile', { ...profile, avatar: 'data:image/svg+xml,<svg/>' }, a)).status, 400);
  assert.equal((await call('auth/profile', { ...profile, avatar: 'data:image/jpeg;base64,YmFk' }, a)).status, 400);
  assert.equal((await call('auth/profile', { ...profile, ownerId: 'other' }, a)).status, 400);
  // Large binary envelope exercises the route's upload limit, not a renderer.
  const bytes = Buffer.alloc(15000); bytes[0] = 255; bytes[1] = 216; bytes[14998] = 255; bytes[14999] = 217;
  const avatar = 'data:image/jpeg;base64,' + bytes.toString('base64');
  let r = await call('auth/profile', { ...profile, avatar }, a); assert.equal(r.status, 200);
  let user = (await r.json()).user; assert.equal(user.displayName, 'Alice'); assert.match(user.avatar, /^\/api\/auth\/avatar\?v=/); assert.equal(user.passwordHash, undefined);
  assert.deepEqual(uploaded[0].image, bytes);
  const stored = await db.collection('users').findOne({ email: 'a@example.test' });
  assert.equal(stored.avatar, ''); assert.equal(stored.avatarKey, uploaded[0].key);
  user = (await (await call('auth/me', undefined, a)).json()).user; assert.match(user.avatar, /^\/api\/auth\/avatar\?v=/);
  const photo = await fetch(base + '/api/auth/avatar', { headers: { cookie: a }, redirect: 'manual' });
  assert.equal(photo.status, 302); assert.equal(photo.headers.get('location'), `https://example.test/${stored.avatarKey}?signed=1`);
  assert.equal((await call('auth/avatar')).status, 401);
  r = await call('auth/profile', { displayName: 'Alice', email: 'a@example.test' }, a);
  assert.equal(r.status, 200); assert.match((await r.json()).user.avatar, /^\/api\/auth\/avatar\?v=/);
  const upload = storage.upload;
  storage.upload = async () => { throw new (require('@nestjs/common').ServiceUnavailableException)('Upload failed'); };
  assert.equal((await call('auth/profile', { ...profile, avatar }, a)).status, 503);
  assert.equal((await db.collection('users').findOne({ _id: stored._id })).avatarKey, stored.avatarKey);
  storage.upload = upload;
  assert.equal((await call('auth/profile', { ...profile, avatar }, a)).status, 200);
  assert.deepEqual(removed, [stored.avatarKey]);
  const other = (await (await call('auth/me', undefined, b)).json()).user; assert.equal(other.displayName, ''); assert.equal(other.avatar, '');
  assert.equal((await (await call('friends', undefined, a)).json()).name, 'Alice');
  assert.equal((await call('auth/profile', { ...profile, email: 'new@example.test' }, a)).status, 400);
  assert.equal((await call('auth/profile', { ...profile, email: 'new@example.test', currentPassword: 'incorrect' }, a)).status, 400);
  assert.equal((await call('auth/profile', { ...profile, email: 'b@example.test', currentPassword: password }, a)).status, 409);
  r = await call('auth/profile', { ...profile, email: 'NEW@example.test', currentPassword: password }, a); assert.equal(r.status, 200);
  user = (await r.json()).user; assert.equal(user.email, 'new@example.test'); assert.equal(user.avatar, '');
  assert.equal((await call('auth/login', { email: 'a@example.test', password })).status, 401);
  assert.equal((await call('auth/login', { email: 'new@example.test', password })).status, 200);
});
